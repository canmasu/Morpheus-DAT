#!/usr/bin/env python3
"""Generates src/config/lzChains.ts from LayerZero's published metadata:
   python3 scripts/gen-lz-chains.py [metadata.json]
Refuses a mainnet chain that lacks two independent verifiers (DVNs) shared with Base."""
import json, sys, urllib.request, pathlib

URL = 'https://metadata.layerzero-api.com/v1/metadata'
# Each passed scripts/dry-run-bridge.ts on a fork against LayerZero's live contracts. Add a chain only after it passes.
MAINNET = ['ethereum', 'bsc', 'optimism', 'polygon', 'linea', 'scroll', 'mantle', 'monad', 'robinhood', 'arc', 'megaeth', 'conflux']
# Not yet passed. Failed on a fork, cause not investigated: arbitrum, avalanche, sonic, hyperliquid, sei.
# RPC did not respond: bera, unichain, plasma. Not run: katana, worldchain, ink, celo, xlayer, stable.
TESTNET = ['bsc-testnet', 'sepolia-testnet', 'arbitrum-sepolia', 'optimism-sepolia', 'amoy-testnet', 'monad-testnet',
           'robinhood-testnet', 'arc-testnet']
# conflux-testnet is left out: LayerZero's endpoint there has no default route to Base Sepolia (getSendLibrary reverts).
NAMES = {'base': 'Base', 'base-sepolia': 'Base Sepolia', 'ethereum': 'Ethereum', 'conflux': 'Conflux eSpace', 'bsc': 'BNB Chain', 'linea': 'Linea', 'bera': 'Berachain', 'hyperliquid': 'HyperEVM', 'xlayer': 'X Layer', 'arc': 'Arc', 'robinhood': 'Robinhood Chain',
         'worldchain': 'World Chain', 'megaeth': 'MegaETH', 'sepolia-testnet': 'Sepolia', 'bsc-testnet': 'BNB Testnet',
         'arbitrum-sepolia': 'Arbitrum Sepolia', 'optimism-sepolia': 'Optimism Sepolia', 'amoy-testnet': 'Polygon Amoy',
         'monad-testnet': 'Monad Testnet', 'robinhood-testnet': 'Robinhood Testnet', 'arc-testnet': 'Arc Testnet'}
# Conflux's own public RPCs; the metadata lists third-party ones first.
RPC = {'conflux': 'https://evm.confluxrpc.com'}
# LayerZero's data has an old or awkward symbol for these.
NATIVE = {'sepolia-testnet': 'ETH', 'polygon': 'POL', 'amoy-testnet': 'POL'}
SECOND = ['nethermind', 'horizen-labs', 'deutsche-telekom', 'google-cloud', 'p2p', 'canary']

src = sys.argv[1] if len(sys.argv) > 1 else None
data = json.load(open(src) if src else urllib.request.urlopen(urllib.request.Request(URL, headers={'user-agent': 'curl/8'})))

def dvns(key):
    out = {}
    for addr, x in data[key].get('dvns', {}).items():
        if x.get('deprecated') or x.get('version') != 2 or x.get('lzReadCompatible'):
            continue
        out.setdefault(x.get('id') or x.get('canonicalName'), addr)
    return out

def entry(key, stage, others=()):
    v = data[key]
    dep = next(x for x in v['deployments'] if x.get('version') == 2 and x.get('stage') == stage)
    det = v['chainDetails']
    rpc = RPC.get(key) or next(r['url'] for r in v['rpcs'] if '$' not in r['url'])
    nat = det['nativeCurrency']
    e = {
        'key': key, 'name': NAMES.get(key, v.get('chainName', key).title()), 'chainId': det['nativeChainId'], 'eid': int(dep['eid']),
        'endpoint': dep['endpointV2']['address'], 'sendLib': dep['sendUln302']['address'], 'receiveLib': dep['receiveUln302']['address'],
        'executor': dep['executor']['address'], 'native': {'name': nat['name'].split()[0], 'symbol': NATIVE.get(key) or nat['symbol'].split()[0], 'decimals': nat.get('decimals', 18)},
        'rpc': rpc, 'explorer': (v.get('blockExplorers') or [{}])[0].get('url', ''),
    }
    here = dvns(key)
    e['dvns'] = {n: here[n] for n in ['layerzero-labs'] + SECOND if n in here}
    if stage == 'mainnet':
        for other in others:
            common = [n for n in e['dvns'] if n in dvns(other)]
            if 'layerzero-labs' not in common or len(common) < 2:
                raise SystemExit(f'{key}: needs two verifiers shared with {other}, found {common}')
    return e

main = [entry(k, 'mainnet', ['base', 'ethereum']) for k in MAINNET]
test = [entry(k, 'testnet') for k in TESTNET]
body = f"""// Generated by scripts/gen-lz-chains.py from {URL}. Do not edit.
import type {{ Address }} from 'viem';

export type LzChain = {{
  key: string;
  name: string;
  chainId: number;
  /** LayerZero's own chain ID. */
  eid: number;
  endpoint: Address;
  sendLib: Address;
  receiveLib: Address;
  executor: Address;
  native: {{ name: string; symbol: string; decimals: number }};
  rpc: string;
  explorer: string;
  /** Verifiers on this chain by name, most preferred first. A path uses the first two both chains share. */
  dvns: Record<string, Address>;
}};

export const LZ_BASE: LzChain = {json.dumps(entry('base', 'mainnet'), indent=2)};
export const LZ_BASE_SEPOLIA: LzChain = {json.dumps(entry('base-sepolia', 'testnet'), indent=2)};
export const LZ_ETHEREUM: LzChain = {json.dumps(entry('ethereum', 'mainnet'), indent=2)};
export const LZ_SEPOLIA: LzChain = {json.dumps(entry('sepolia-testnet', 'testnet'), indent=2)};

/** Token home chains that can bridge to Base. */
export const LZ_MAINNET_CHAINS: LzChain[] = {json.dumps(main, indent=2)};
export const LZ_TESTNET_CHAINS: LzChain[] = {json.dumps(test, indent=2)};
"""
pathlib.Path(__file__).resolve().parent.parent.joinpath('src/config/lzChains.ts').write_text(body)
for e in main + test:
    print(f"{e['name']:20} {e['chainId']:>10} eid {e['eid']} {list(e['dvns'])[:3]}")
