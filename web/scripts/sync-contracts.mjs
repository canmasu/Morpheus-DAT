// Copies ABI + bytecode for the deployable contracts from ../contracts/out into src/contracts/artifacts.ts.
// Run after `forge build` whenever the contracts change.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, '..', 'contracts', 'out');
// [contract, source file] — MockERC20 is the open-mint test token used for tEXM on testnet.
const names = [
  ...['ArbFeeConfig', 'MorSplitter', 'SplitterDeployer'].map((n) => [n, n]),
  ...['MorpheusAdapter', 'ExitOnlyAdapter', 'CapitalAccount', 'PoolVault', 'PoolFactory', 'OTCMarket'].map((n) => [n, n]),
  ['MockERC20', 'Mocks'],
];

let ts = '// Generated by scripts/sync-contracts.mjs from contracts/out. Do not edit.\n\n';
for (const [n, file] of names) {
  const a = JSON.parse(readFileSync(join(out, `${file}.sol`, `${n}.json`), 'utf8'));
  ts += `export const ${n} = {\n  abi: ${JSON.stringify(a.abi)} as const,\n  bytecode: '${a.bytecode.object}' as \`0x\${string}\`,\n} as const;\n\n`;
}
writeFileSync(join(root, 'src', 'contracts', 'artifacts.ts'), ts);
console.log(`synced ${names.length} contracts`);
