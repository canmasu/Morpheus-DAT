// Copies ABI + bytecode for the deployable contracts from ../contracts/out into src/contracts/artifacts.ts.
// Run after `forge build` whenever the contracts change.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, '..', 'contracts', 'out');
// [contract, source file] — MockERC20 is the open-mint test token used for tEXM on testnet.
const names = [
  ...['ArbFeeConfig', 'MorSplitter', 'SplitterDeployer'].map((n) => [n, n]),
  ...['MorpheusAdapter', 'ExitOnlyAdapter', 'CapitalAccount', 'PoolVault', 'PoolFactory', 'OTCMarket'].map((n) => [n, n]),
  ...['BuildersAdapter', 'BuildersExitAdapter', 'BuilderVault', 'BuilderPoolFactory'].map((n) => [n, n]),
  ['MockERC20', 'Mocks'],
];

let ts = '// Generated by scripts/sync-contracts.mjs from contracts/out. Do not edit.\n\n';
// Testnet only: Morpheus's Builders contracts, compiled in contracts/sim-builders with Morpheus's own settings.
const simOut = join(root, '..', 'contracts', 'sim-builders', 'out');
// The Partner's own bridge contracts, compiled in contracts/oft-kit.
const kitOut = join(root, '..', 'contracts', 'oft-kit', 'out');
const kit = ['OGTokenAdapter', 'OGTokenOFT', 'OGBridgeRegistry'];
const sim = ['LinearDistributionIntervalDecrease', 'RewardPool', 'FeeConfig', 'BuildersTreasuryV2', 'BuildersV4', 'SimSetup'];
for (const [n, file, dir] of [...names.map(([n, f]) => [n, f, out]), ...sim.map((n) => [n, n, simOut]), ...kit.map((n) => [n, n, kitOut])]) {
  const a = JSON.parse(readFileSync(join(dir, `${file}.sol`, `${n}.json`), 'utf8'));
  ts += `export const ${n} = {\n  abi: ${JSON.stringify(a.abi)} as const,\n  bytecode: '${a.bytecode.object}' as \`0x\${string}\`,\n} as const;\n\n`;
}
writeFileSync(join(root, 'src', 'contracts', 'artifacts.ts'), ts);
console.log(`synced ${names.length + sim.length + kit.length} contracts`);
